/**
 * Generates db/seed.sql from the demo data so the database and the app never
 * drift apart. Run: npx tsx db/generate-seed.ts
 */
import { writeFileSync } from 'node:fs';
import { DESTINATIONS } from '../src/data/destinations';
import { TRIPS } from '../src/data/trips';
import { MONTHS } from '../src/types/travel';

const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
const arr = (values: (string | number)[]) => `ARRAY[${values.map((v) => (typeof v === 'number' ? v : q(v))).join(', ')}]${values.length && typeof values[0] === 'number' ? '::SMALLINT[]' : '::TEXT[]'}`;

const lines: string[] = ['-- Generated by db/generate-seed.ts — demo data only, prices illustrative.', 'BEGIN;'];
for (const d of DESTINATIONS) {
  lines.push(`INSERT INTO destination VALUES (${q(d.id)}, ${q(d.name)}, ${q(d.country)}, ${q(d.region)}, ${d.hasBeach}, ${d.flightHoursFromLondon}, ${q(d.summary)});`);
  MONTHS.forEach((m, i) => lines.push(`INSERT INTO destination_climate VALUES (${q(d.id)}, ${i + 1}, ${d.temperatureByMonth[m]});`));
  d.activities.forEach((a, i) => lines.push(`INSERT INTO destination_activity VALUES (${q(d.id)}, ${i + 1}, ${q(a)});`));
}
for (const t of TRIPS) {
  const hotelId = `hotel-${t.id.slice(5)}`;
  lines.push(
    `INSERT INTO hotel VALUES (${q(hotelId)}, ${q(t.destinationId)}, ${q(t.hotelName)}, ${t.hotelRating}, ${t.beachDistance ?? 'NULL'}, ${t.nightlifeScore}, ${t.familyFriendly}, ${t.coupleFriendly}, ${arr(t.amenities)});`,
  );
  lines.push(
    `INSERT INTO package VALUES (${q(t.id)}, ${q(hotelId)}, ${t.price * 100}, 'GBP', ${t.nights}, ${q(t.boardBasis)}, ${q(t.departureAirport)}, ${q(t.description)}, ${arr(t.holidayTypes)}, ${arr(t.availableMonths.map((m) => MONTHS.indexOf(m) + 1))});`,
  );
}
lines.push('COMMIT;', '');
writeFileSync(new URL('./seed.sql', import.meta.url), lines.join('\n'));
console.log(`Wrote ${DESTINATIONS.length} destinations and ${TRIPS.length} packages to db/seed.sql`);
